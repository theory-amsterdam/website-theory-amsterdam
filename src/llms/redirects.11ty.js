// /_redirects (Netlify) — permanent redirects from the old Hugo profile URLs.
//
// The Hugo site served profiles at /author/<urlized display name>/ (plus an RSS feed at
// .../index.xml); Eleventy serves them at /authors/<slug>/. Google still crawls the old URLs
// and reports them as 404s in Search Console. Every current profile gets a redirect from the
// Hugo form of its title; people whose title has changed since need an entry in ALIASES.
// People who have left (alumni table only) are deliberately not redirected: 404 is correct.
const ALIASES = {
  "sarah-li": "li", // now "Sarah Meng Li"
};

// Hugo's urlize: strip diacritics, lowercase, whitespace -> "-", keep everything else (dots too).
const hugoSlug = (title) =>
  title
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "-");

module.exports = class {
  data() {
    return { permalink: "/_redirects" };
  }

  render({ collections }) {
    const targets = new Map();
    for (const a of collections.authors) targets.set(hugoSlug(a.data.title), a.page.fileSlug);
    for (const [old, slug] of Object.entries(ALIASES))
      if (collections.authors.some((a) => a.page.fileSlug === slug)) targets.set(old, slug);
    const lines = [...targets]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([old, slug]) => `/author/${old}/*  /authors/${slug}/  301`);
    return `# Generated by src/llms/redirects.11ty.js — old Hugo profile URLs.\n${lines.join("\n")}\n`;
  }
};
