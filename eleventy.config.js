const { rawBody } = require("./src/_includes/markdown.js");
const { RenderPlugin } = require("@11ty/eleventy");

module.exports = function (eleventyConfig) {
  eleventyConfig.addPlugin(RenderPlugin);

  eleventyConfig.ignores.add("**/_site/**");
  // Homepage prose partials are rendered via {% renderFile %} from home/index.njk;
  // ignore them as standalone templates so they don't emit /home/sections/<slug>/ pages.
  eleventyConfig.ignores.add("src/home/sections/**/*.md");

  eleventyConfig.addFilter("dateISO", (d) => {
    const date = d instanceof Date ? d : new Date(d);
    return date.toISOString().slice(0, 10);
  });

  eleventyConfig.addFilter("dateLong", (d) => {
    const date = d instanceof Date ? d : new Date(d);
    return date.toLocaleDateString("en-GB", {
      year: "numeric",
      month: "long",
      day: "numeric",
    });
  });

  eleventyConfig.addFilter("excerpt", (html) => {
    if (!html) return "";
    const idx = html.indexOf("<!--more-->");
    return idx >= 0 ? html.slice(0, idx) : html;
  });

  eleventyConfig.addFilter("readTime", (html) => {
    if (!html) return 1;
    const words = html.replace(/<[^>]+>/g, " ").trim().split(/\s+/).length;
    return Math.max(1, Math.round(words / 200));
  });

  eleventyConfig.addPassthroughCopy({ "src/assets": "assets" });
  eleventyConfig.addPassthroughCopy("src/authors/**/*.{jpg,jpeg,png,gif,webp,JPG,JPEG,PNG}");
  eleventyConfig.addPassthroughCopy("src/history/**/*.{jpg,jpeg,png,gif,webp,JPG,JPEG,PNG}");
  // Posts live under src/posts/ but render at /post/<slug>/ — remap so relative
  // image refs in post bodies resolve against the rendered page URL.
  // Images only: the .md sources would otherwise be published raw (frontmatter, drafts) next to
  // the clean Markdown mirrors generated by src/llms/mirror.njk; .js is the directory data file.
  eleventyConfig.addPassthroughCopy(
    { "src/posts": "post" },
    { filter: (file) => !/\.(md|js)$/i.test(file) }
  );

  // ---- Machine-readable outputs (src/llms/, layout.njk <head>) ----

  // Body of a source file without its frontmatter — the Markdown mirrors serve this verbatim.
  eleventyConfig.addFilter("rawBody", rawBody);

  // Plain one-line text from rendered HTML, for meta descriptions.
  eleventyConfig.addFilter("plainText", (html) =>
    (html || "")
      .replace(/<[^>]+>/g, " ")
      .replace(/&nbsp;/g, " ")
      .replace(/&amp;/g, "&")
      .replace(/\s+/g, " ")
      .trim()
  );

  // Mailto links stay off the bulk outputs (llms-full.txt, JSON-LD).
  eleventyConfig.addFilter("withoutMailto", (social) =>
    (social || []).filter((s) => s.link && !s.link.startsWith("mailto:"))
  );

  // Every page whose source is Markdown gets a mirror at <url>index.html.md.
  eleventyConfig.addCollection("mdPages", (collectionApi) =>
    collectionApi
      .getAll()
      .filter((item) => item.inputPath.endsWith(".md") && item.url && item.url.endsWith("/"))
  );

  const firstName = (entry) => (entry.data.title || "").trim().split(/\s+/)[0] || "";

  eleventyConfig.addCollection("authors", (collectionApi) =>
    collectionApi
      .getFilteredByGlob("src/authors/**/index.md")
      .sort((a, b) => {
        const byLast = (a.data.lastname || "").localeCompare(b.data.lastname || "");
        if (byLast !== 0) return byLast;
        return firstName(a).localeCompare(firstName(b));
      })
  );

  return {
    dir: {
      input: "src",
      output: "_site",
      includes: "_includes",
      data: "_data",
    },
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk",
    templateFormats: ["njk", "md", "html", "11ty.js"],
  };
};
